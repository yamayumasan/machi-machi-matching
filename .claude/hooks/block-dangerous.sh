#!/bin/bash
# =============================================================================
# block-dangerous.sh — 危険コマンドブロック
# =============================================================================
#
# PreToolUse (Bash) で呼び出される
# 危険なコマンドパターンをブロック
#
# =============================================================================

set -euo pipefail

# =============================================================================
# ブロック対象パターン
# =============================================================================

DANGEROUS_PATTERNS=(
  "rm -rf"
  "rm -fr"
  "sudo "
  "curl[[:space:]].*[|][[:space:]]*(sh|bash|zsh)([[:space:]]|$)"
  "wget[[:space:]].*[|][[:space:]]*(sh|bash|zsh)([[:space:]]|$)"
  "chmod 777"
  "> /dev/sd"
  "mkfs"
  "dd if="
)

# =============================================================================
# メイン処理
# =============================================================================

# 標準入力からJSONを読み取り
INPUT=$(cat)

# コマンドを抽出
COMMAND=$(echo "$INPUT" | jq -r '.tool_input.command // ""' 2>/dev/null || echo "")

if [ -z "$COMMAND" ]; then
  exit 0
fi

# 危険パターンチェック
for pattern in "${DANGEROUS_PATTERNS[@]}"; do
  if echo "$COMMAND" | grep -qE "$pattern"; then
    echo "ブロック: 危険なコマンドパターン '$pattern' が検出されました" >&2
    exit 2
  fi
done

exit 0
